// `melzin types`: generated source for each schema shape, the CLI's output files and its refusal on
// checker errors.

import { afterAll, beforeAll, describe, expect, test } from 'bun:test'
import { copyFileSync, existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { loadViewFile } from '../src/cli/check.ts'
import { generateTypes, typesPathFor } from '../src/cli/types.ts'

const cli = join(import.meta.dir, '../src/cli/index.ts')
const fixtures = join(import.meta.dir, 'fixtures/types')
let dir = ''

async function run(args: string[]): Promise<{ code: number; stdout: string; stderr: string }> {
  const proc = Bun.spawn(['bun', cli, 'types', ...args], { cwd: dir, stdout: 'pipe', stderr: 'pipe' })
  const [stdout, stderr, code] = await Promise.all([new Response(proc.stdout).text(), new Response(proc.stderr).text(), proc.exited])
  return { code, stdout, stderr }
}

async function generated(name: string): Promise<string> {
  const view = await loadViewFile(join(fixtures, `${name}.melzin.html`))
  expect(view.issues).toEqual([])
  return generateTypes(view.schema, `${name}.melzin.html`)
}

beforeAll(() => {
  dir = mkdtempSync(join(tmpdir(), 'melzin-types-'))
  for (const name of readdirSync(fixtures)) copyFileSync(join(fixtures, name), join(dir, name))
})

afterAll(() => {
  rmSync(dir, { recursive: true, force: true })
})

describe('generateTypes', () => {
  test('the counter (exactly the brief\'s example)', async () => {
    expect(await generated('counter')).toBe(
      [
        '// Generated by `melzin types` from counter.melzin.html. Do not edit.',
        'export type Data = {',
        '  count: number',
        '}',
        'export type Handlers = {',
        '  increment: (payload?: undefined) => void',
        '}',
        '',
      ].join('\n'),
    )
  })

  test('leaf types, optional fields and descriptions as comments', async () => {
    expect(await generated('leaves')).toBe(
      [
        '// Generated by `melzin types` from leaves.melzin.html. Do not edit.',
        'export type Data = {',
        '  /** Shown above the value */',
        '  label: string',
        '  amount: number',
        '  active?: boolean',
        '}',
        'export type Handlers = {',
        '  /** Saves the *\\/ form */',
        '  save: (payload?: undefined) => void',
        '  cancel: (payload?: undefined) => void',
        '}',
        '',
      ].join('\n'),
    )
  })

  test('nested objects', async () => {
    expect(await generated('nested')).toBe(
      [
        '// Generated by `melzin types` from nested.melzin.html. Do not edit.',
        'export type Data = {',
        '  user: {',
        '    name: string',
        '    stats?: {',
        '      followers: number',
        '    }',
        '  }',
        '}',
        'export type Handlers = {',
        '  follow: (payload?: undefined) => void',
        '}',
        '',
      ].join('\n'),
    )
  })

  test('no data', async () => {
    expect(await generated('no-data')).toBe(
      [
        '// Generated by `melzin types` from no-data.melzin.html. Do not edit.',
        'export type Data = Record<string, never>',
        'export type Handlers = {',
        '  dismiss: (payload?: undefined) => void',
        '}',
        '',
      ].join('\n'),
    )
  })

  test('no events', async () => {
    expect(await generated('no-events')).toBe(
      [
        '// Generated by `melzin types` from no-events.melzin.html. Do not edit.',
        'export type Data = {',
        '  message?: string',
        '}',
        'export type Handlers = Record<string, never>',
        '',
      ].join('\n'),
    )
  })

  test('no schema at all, and empty objects', async () => {
    expect(await generated('static')).toBe(
      [
        '// Generated by `melzin types` from static.melzin.html. Do not edit.',
        'export type Data = Record<string, never>',
        'export type Handlers = Record<string, never>',
        '',
      ].join('\n'),
    )
    const schema = { data: { type: 'object' as const, properties: { box: { type: 'object' as const, properties: {} } } }, events: {} }
    expect(generateTypes(schema, 'x.melzin.html')).toContain('  box?: Record<string, never>\n')
  })

  test('typesPathFor', () => {
    expect(typesPathFor('/p/views/counter.melzin.html')).toBe('/p/views/counter.types.ts')
    expect(typesPathFor('views/profile-card.melzin.html')).toBe('views/profile-card.types.ts')
  })
})

describe('melzin types', () => {
  test('writes <name>.types.ts next to each view', async () => {
    const { code, stdout } = await run(['counter.melzin.html', 'nested.melzin.html'])
    expect(code).toBe(0)
    expect(stdout).toBe('wrote counter.types.ts\nwrote nested.types.ts\n')
    expect(readFileSync(join(dir, 'counter.types.ts'), 'utf8')).toBe(await generated('counter'))
    expect(readFileSync(join(dir, 'nested.types.ts'), 'utf8')).toBe(await generated('nested'))
  })

  test('leaves an up-to-date file untouched', async () => {
    await run(['leaves.melzin.html'])
    const before = statSync(join(dir, 'leaves.types.ts')).mtimeMs
    await Bun.sleep(20)
    const { code, stdout } = await run(['leaves.melzin.html'])
    expect(code).toBe(0)
    expect(stdout).toBe('leaves.types.ts is up to date\n')
    expect(statSync(join(dir, 'leaves.types.ts')).mtimeMs).toBe(before)
  })

  test('warnings do not block generation', async () => {
    const { code } = await run(['warned.melzin.html'])
    expect(code).toBe(0)
    expect(existsSync(join(dir, 'warned.types.ts'))).toBe(true)
  })

  test('refuses (exit 1) when the view has checker errors, and still writes the others', async () => {
    const { code, stdout, stderr } = await run(['broken.melzin.html', 'no-events.melzin.html'])
    expect(code).toBe(1)
    expect(stderr).toBe(
      [
        "broken.melzin.html:14:14: error: m-text: unknown field 'cuont' (did you mean 'count'?)",
        'melzin types: not writing broken.types.ts: broken.melzin.html has 1 error (run melzin check)',
        '',
      ].join('\n'),
    )
    expect(stdout).toBe('wrote no-events.types.ts\n')
    expect(existsSync(join(dir, 'broken.types.ts'))).toBe(false)
  })

  test('refuses files that are not views or do not exist', async () => {
    const { code, stderr } = await run(['missing.melzin.html'])
    expect(code).toBe(1)
    expect(stderr).toContain("missing.melzin.html:1:1: error: can't read the file: file not found")
    expect(existsSync(join(dir, 'missing.types.ts'))).toBe(false)
  })

  test('no files is a usage error (exit 2)', async () => {
    const { code, stderr } = await run([])
    expect(code).toBe(2)
    expect(stderr).toContain('usage: melzin types <files...>')
  })
})
