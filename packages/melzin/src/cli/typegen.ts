// Generates a view's host types from its schema (used by `melzin types`, and by `melzin check` to spot
// a stale types file).

import { basename, dirname, join } from 'node:path'
import { type MelzinSchema, type ObjectSchema, VIEW_FILE_SUFFIX } from '../core/index.ts'

const EMPTY = 'Record<string, never>'

function comment(description: string | undefined, indent: string): string[] {
  if (description === undefined || description.trim() === '') return []
  const text = description.replace(/\s+/g, ' ').trim().replaceAll('*/', '*\\/')
  return [`${indent}/** ${text} */`]
}

function objectType(object: ObjectSchema, indent: string): string {
  const entries = Object.entries(object.properties)
  if (entries.length === 0) return EMPTY
  const required = new Set(object.required ?? [])
  const inner = `${indent}  `
  const lines = ['{']
  for (const [name, field] of entries) {
    lines.push(...comment(field.description, inner))
    const type = field.type === 'object' ? objectType(field, inner) : field.type
    lines.push(`${inner}${name}${required.has(name) ? '' : '?'}: ${type}`)
  }
  lines.push(`${indent}}`)
  return lines.join('\n')
}

function handlersType(events: MelzinSchema['events']): string {
  const entries = Object.entries(events ?? {})
  if (entries.length === 0) return EMPTY
  const lines = ['{']
  for (const [name, event] of entries) {
    lines.push(...comment(event.description, '  '))
    lines.push(`  ${name}: (payload?: undefined) => void`)
  }
  lines.push('}')
  return lines.join('\n')
}

/** The `.types.ts` source for a view. `sourceName` is the view's file name, for the header. */
export function generateTypes(schema: MelzinSchema | null, sourceName: string): string {
  const data = schema?.data === undefined ? EMPTY : objectType(schema.data, '')
  return [
    `// Generated by \`melzin types\` from ${sourceName}. Do not edit.`,
    `export type Data = ${data}`,
    `export type Handlers = ${handlersType(schema?.events)}`,
    '',
  ].join('\n')
}

/** `views/counter.mel.html` → `views/counter.types.ts`. */
export function typesPathFor(viewPath: string): string {
  const name = basename(viewPath)
  const stem = name.endsWith(VIEW_FILE_SUFFIX) ? name.slice(0, -VIEW_FILE_SUFFIX.length) : name.replace(/\.[^.]*$/, '')
  return join(dirname(viewPath), `${stem}.types.ts`)
}
