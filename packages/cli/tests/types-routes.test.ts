// Types for routes: Href on link fields, routes.types.ts from routes.json, `melzin types routes.json`,
// and tsc on typed sources and href helpers (SPEC D20, D23).

import { afterAll, beforeAll, describe, expect, test } from 'bun:test'
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { validateRouteTable } from 'melzin/core'
import { generateRouteTypes, generateTypes } from '../src/types.ts'

const root = join(import.meta.dir, '..')
const cli = join(root, 'src/index.ts')
const tsc = join(root, 'node_modules/.bin/tsc')
const runtime = join(root, '../melzin/src/runtime/index.ts')

const ROUTES = {
  routes: {
    home: { path: '/', view: 'home', query: { as: {} } },
    profile: { path: '/u/:handle', view: 'profile', query: { as: {} }, description: 'Someone\'s profile' },
    profileCard: { path: '/card/:handle', view: 'profile-card' },
  },
}

function view(schema: unknown, body: string, snapshots: unknown): string {
  return `<!doctype html><html><head><title>V</title><script type="melzin/schema">${JSON.stringify(schema)}</script><script type="melzin/snapshots">${JSON.stringify(snapshots)}</script></head><body>${body}</body></html>\n`
}

const HOME = view(
  { data: { type: 'object', properties: { anaUrl: { type: 'string', route: 'profile' } }, required: ['anaUrl'] } },
  '<a m-bind:href="anaUrl">Ana</a>',
  { s: { data: { anaUrl: '/u/ana' } } },
)
// A list of links (D34) and an event with a payload (D35).
const PROFILE = view(
  {
    data: {
      type: 'object',
      properties: {
        name: { type: 'string' },
        homeUrl: { type: 'string', route: 'home' },
        followers: {
          type: 'array',
          key: 'handle',
          items: { type: 'object', properties: { handle: { type: 'string' }, url: { type: 'string', route: 'profile' } }, required: ['handle', 'url'] },
        },
      },
      required: ['name'],
    },
    events: { follow: { payload: { type: 'object', properties: { handle: { type: 'string' } }, required: ['handle'] } } },
  },
  `<h1 m-text="name"></h1><a m-bind:href="homeUrl">Home</a><button m-on:click="emit('follow', { handle: route.params.handle })">Follow</button>
<ul><li m-for="follower in followers"><a m-bind:href="follower.url" m-text="follower.handle"></a></li></ul>`,
  { s: { data: { name: 'Ana', homeUrl: '/', followers: [] }, route: { params: { handle: 'ana' } } } },
)
const CARD = view({ data: { type: 'object', properties: { name: { type: 'string' } }, required: ['name'] } }, '<p m-text="name"></p>', { s: { data: { name: 'Ana' } } })

describe('generated source', () => {
  test('link fields are Href', () => {
    const schema = { data: { type: 'object' as const, properties: { url: { type: 'string' as const, route: 'home' }, name: { type: 'string' as const } }, required: ['url'] } }
    expect(generateTypes(schema, 'x.mel.html')).toBe(
      [
        '// Generated by `melzin types` from x.mel.html. Do not edit.',
        "import type { Href } from 'melzin'",
        '',
        'export type Data = {',
        "  url: Href<'home'>",
        '  name?: string',
        '}',
        'export type Handlers = Record<string, never>',
        '',
      ].join('\n'),
    )
  })

  test('routes.types.ts', () => {
    const table = validateRouteTable(ROUTES).table!
    expect(generateRouteTypes(table, (name) => `./views/${name}.types.ts`)).toBe(
      [
        '// Generated by `melzin types` from routes.json. Do not edit.',
        "import type * as HomeView from './views/home.types.ts'",
        "import type * as ProfileView from './views/profile.types.ts'",
        "import type * as ProfileCardView from './views/profile-card.types.ts'",
        '',
        'export type Routes = {',
        '  /** /, shown by home.mel.html */',
        '  home: {',
        '    params: Record<string, never>',
        '    query: { as?: string }',
        '    data: HomeView.Data',
        '    handlers: HomeView.Handlers',
        '  }',
        "  /** Someone's profile */",
        '  profile: {',
        '    params: { handle: string }',
        '    query: { as?: string }',
        '    data: ProfileView.Data',
        '    handlers: ProfileView.Handlers',
        '  }',
        '  /** /card/:handle, shown by profile-card.mel.html */',
        '  profileCard: {',
        '    params: { handle: string }',
        '    query: Record<string, never>',
        '    data: ProfileCardView.Data',
        '    handlers: ProfileCardView.Handlers',
        '  }',
        '}',
        '',
      ].join('\n'),
    )
    expect(generateRouteTypes({ routes: [] }, () => '')).toBe('// Generated by `melzin types` from routes.json. Do not edit.\nexport type Routes = Record<string, never>\n')
  })
})

describe('a typed app', () => {
  let dir = ''
  let typesRun = { code: -1, stdout: '', stderr: '' }
  let output = ''

  /** Each file is a source for the app; `errors` lists the TS error codes it must produce. */
  const apps: { file: string; body: string; errors: string[] }[] = [
    {
      file: 'app-ok.ts',
      errors: [],
      body: `
        const href = hrefs<Routes>(routes)
        const app = await startApp<Routes>(el, {
          routes,
          source: {
            home: { load: ({ query }) => ({ anaUrl: href('profile', { handle: 'ana' }, { as: query.as }) }) },
            profile: {
              load: async ({ params }) => ({
                name: params.handle,
                homeUrl: href('home'),
                followers: [{ handle: 'bo', url: href('profile', { handle: 'bo' }) }],
              }),
              on: { follow: ({ handle }, page) => page.update({ ...page.data, name: handle }) },
            },
            profileCard: { load: () => ({ name: 'x' }) },
          },
          navigate: (to) => (to.name === 'profileCard' ? href('home') : undefined),
        })
        const name: string | undefined = app.route?.name
        void name`,
    },
    {
      file: 'app-hand-built-link.ts',
      errors: ['TS2322'],
      body: `
        await startApp<Routes>(el, {
          routes,
          source: {
            home: { load: () => ({ anaUrl: '/u/ana' }) },
            profile: { load: () => ({ name: 'x' }), on: { follow() {} } },
            profileCard: { load: () => ({ name: 'x' }) },
          },
        })`,
    },
    {
      file: 'app-wrong-route-link.ts',
      errors: ['TS2322'],
      body: `
        const href = hrefs<Routes>(routes)
        await startApp<Routes>(el, {
          routes,
          source: {
            home: { load: () => ({ anaUrl: href('home') }) },
            profile: { load: () => ({ name: 'x' }), on: { follow() {} } },
            profileCard: { load: () => ({ name: 'x' }) },
          },
        })`,
    },
    {
      file: 'app-missing-handler.ts',
      errors: ['TS2741'],
      body: `
        await startApp<Routes>(el, {
          routes,
          source: {
            home: { load: () => ({ anaUrl: hrefs<Routes>(routes)('profile', { handle: 'a' }) }) },
            profile: { load: () => ({ name: 'x' }), on: {} },
            profileCard: { load: () => ({ name: 'x' }) },
          },
        })`,
    },
    {
      file: 'app-missing-route.ts',
      errors: ['TS2741'],
      body: `
        await startApp<Routes>(el, {
          routes,
          source: {
            home: { load: () => ({ anaUrl: hrefs<Routes>(routes)('profile', { handle: 'a' }) }) },
            profile: { load: () => ({ name: 'x' }), on: { follow() {} } },
          },
        })`,
    },
    {
      file: 'app-wrong-payload.ts',
      errors: ['TS2322'],
      body: `
        await startApp<Routes>(el, {
          routes,
          source: {
            home: { load: () => ({ anaUrl: hrefs<Routes>(routes)('profile', { handle: 'a' }) }) },
            profile: { load: () => ({ name: 'x' }), on: { follow: (payload: { handle: number }) => { void payload } } },
            profileCard: { load: () => ({ name: 'x' }) },
          },
        })`,
    },
    {
      file: 'app-hand-built-item-link.ts',
      errors: ['TS2322'],
      body: `
        await startApp<Routes>(el, {
          routes,
          source: {
            home: { load: () => ({ anaUrl: hrefs<Routes>(routes)('profile', { handle: 'a' }) }) },
            profile: { load: () => ({ name: 'x', followers: [{ handle: 'bo', url: '/u/bo' }] }), on: { follow() {} } },
            profileCard: { load: () => ({ name: 'x' }) },
          },
        })`,
    },
    {
      file: 'href-missing-param.ts',
      errors: ['TS2554'],
      body: `const href = hrefs<Routes>(routes)
        href('profile')`,
    },
    {
      file: 'href-wrong-query.ts',
      errors: ['TS2353'],
      body: `const href = hrefs<Routes>(routes)
        href('profile', { handle: 'a' }, { tab: 'x' })`,
    },
    {
      file: 'href-unknown-route.ts',
      errors: ['TS2345'],
      body: `const href = hrefs<Routes>(routes)
        href('nope', {})`,
    },
  ]

  beforeAll(async () => {
    dir = mkdtempSync(join(tmpdir(), 'melzin-routes-types-'))
    mkdirSync(join(dir, 'views'))
    writeFileSync(join(dir, 'routes.json'), JSON.stringify(ROUTES, null, 2))
    writeFileSync(join(dir, 'views/home.mel.html'), HOME)
    writeFileSync(join(dir, 'views/profile.mel.html'), PROFILE)
    writeFileSync(join(dir, 'views/profile-card.mel.html'), CARD)
    const proc = Bun.spawn(['bun', cli, 'types', 'routes.json'], { cwd: dir, stdout: 'pipe', stderr: 'pipe' })
    const [stdout, stderr, code] = await Promise.all([new Response(proc.stdout).text(), new Response(proc.stderr).text(), proc.exited])
    typesRun = { code, stdout, stderr }

    for (const app of apps) {
      writeFileSync(
        join(dir, app.file),
        [
          `import { hrefs, startApp } from ${JSON.stringify(runtime)}`,
          "import type { Routes } from './routes.types.ts'",
          "import routes from './routes.json'",
          'declare const el: Element',
          'export async function main(): Promise<void> {',
          app.body,
          '}',
          '',
        ].join('\n'),
      )
    }
    // Generated view types import Href from 'melzin'; map it to the source.
    writeFileSync(
      join(dir, 'tsconfig.json'),
      JSON.stringify({
        extends: join(root, '../../tsconfig.base.json'),
        compilerOptions: { types: [], paths: { melzin: [runtime] } },
        include: ['*.ts', 'views/*.ts'],
      }),
    )
    const check = Bun.spawn([tsc, '--noEmit', '--pretty', 'false', '-p', dir], { cwd: dir, stdout: 'pipe', stderr: 'pipe' })
    const [out, err] = await Promise.all([new Response(check.stdout).text(), new Response(check.stderr).text(), check.exited])
    output = out + err
  })

  afterAll(() => {
    rmSync(dir, { recursive: true, force: true })
  })

  test('melzin types routes.json writes the route types and the views\' types', () => {
    expect(typesRun.stderr).toBe('')
    expect(typesRun.code).toBe(0)
    expect(typesRun.stdout.trim().split('\n')).toEqual([
      'wrote views/home.types.ts',
      'wrote views/profile.types.ts',
      'wrote views/profile-card.types.ts',
      'wrote routes.types.ts',
    ])
    expect(readFileSync(join(dir, 'routes.types.ts'), 'utf8')).toContain("import type * as HomeView from './views/home.types.ts'")
    expect(existsSync(join(dir, 'views/profile-card.types.ts'))).toBe(true)
  })

  test('tsc ran', () => {
    expect(output).not.toContain('error TS5')
    expect(output.split('\n').filter((line) => line.includes('.types.ts('))).toEqual([])
  })

  for (const app of apps) {
    test(`${app.file} ${app.errors.length === 0 ? 'passes' : `fails with ${app.errors.join(', ')}`}`, () => {
      const lines = output.split('\n').filter((line) => line.startsWith(`${app.file}(`) || line.includes(`/${app.file}(`))
      const codes = [...new Set(lines.map((line) => /error (TS\d+)/.exec(line)?.[1]))]
      expect({ file: app.file, codes, lines }).toEqual({ file: app.file, codes: app.errors, lines: app.errors.length === 0 ? [] : lines })
    })
  }
})
