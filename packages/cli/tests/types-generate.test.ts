// `melzin types`: generated source for each schema shape, the CLI's output files and its refusal on
// checker errors.

import { afterAll, beforeAll, describe, expect, test } from 'bun:test'
import { copyFileSync, existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { loadViewFile } from '../src/check.ts'
import { generateTypes, typesPathFor } from '../src/types.ts'

const cli = join(import.meta.dir, '../src/index.ts')
const fixtures = join(import.meta.dir, 'fixtures/types')
let dir = ''

async function run(args: string[]): Promise<{ code: number; stdout: string; stderr: string }> {
  const proc = Bun.spawn(['bun', cli, 'types', ...args], { cwd: dir, stdout: 'pipe', stderr: 'pipe' })
  const [stdout, stderr, code] = await Promise.all([new Response(proc.stdout).text(), new Response(proc.stderr).text(), proc.exited])
  return { code, stdout, stderr }
}

async function generated(name: string): Promise<string> {
  const view = await loadViewFile(join(fixtures, `${name}.mel.html`))
  expect(view.issues).toEqual([])
  return generateTypes(view.schema, `${name}.mel.html`)
}

beforeAll(() => {
  dir = mkdtempSync(join(tmpdir(), 'melzin-types-'))
  for (const name of readdirSync(fixtures)) copyFileSync(join(fixtures, name), join(dir, name))
})

afterAll(() => {
  rmSync(dir, { recursive: true, force: true })
})

describe('generateTypes', () => {
  test('the counter (exactly the brief\'s example)', async () => {
    expect(await generated('counter')).toBe(
      [
        '// Generated by `melzin types` from counter.mel.html. Do not edit.',
        'export type Data = {',
        '  count: number',
        '}',
        'export type Handlers = {',
        '  increment: (payload?: undefined) => void',
        '}',
        '',
      ].join('\n'),
    )
  })

  test('leaf types, optional fields and descriptions as comments', async () => {
    expect(await generated('leaves')).toBe(
      [
        '// Generated by `melzin types` from leaves.mel.html. Do not edit.',
        'export type Data = {',
        '  /** Shown above the value */',
        '  label: string',
        '  amount: number',
        '  active?: boolean',
        '}',
        'export type Handlers = {',
        '  /** Saves the *\\/ form */',
        '  save: (payload?: undefined) => void',
        '  cancel: (payload?: undefined) => void',
        '}',
        '',
      ].join('\n'),
    )
  })

  test('nested objects', async () => {
    expect(await generated('nested')).toBe(
      [
        '// Generated by `melzin types` from nested.mel.html. Do not edit.',
        'export type Data = {',
        '  user: {',
        '    name: string',
        '    stats?: {',
        '      followers: number',
        '    }',
        '  }',
        '}',
        'export type Handlers = {',
        '  follow: (payload?: undefined) => void',
        '}',
        '',
      ].join('\n'),
    )
  })

  test('lists are arrays inline; payloads type their handlers, with descriptions as comments', async () => {
    expect(await generated('poll')).toBe(
      [
        '// Generated by `melzin types` from poll.mel.html. Do not edit.',
        'export type Data = {',
        '  question: string',
        '  /** In the order to show */',
        '  options: readonly {',
        '    id: string',
        '    label: string',
        '    /** Votes so far */',
        '    votes: number',
        '    note?: string',
        "    /** The viewer's vote */",
        '    mine: boolean',
        '  }[]',
        '  tags?: readonly string[]',
        '}',
        'export type Handlers = {',
        '  /** One vote for an option */',
        '  vote: (payload: { optionId: string; note?: string }) => void',
        '  /** @param payload The option to show first */',
        '  pick: (payload: {',
        '    /** Its votes */',
        '    votes: number',
        '    mine: boolean',
        '  }) => void',
        '  reset: (payload?: undefined) => void',
        '}',
        '',
      ].join('\n'),
    )
  })

  test('an event with both descriptions, an empty payload, and lists of links', () => {
    const schema = {
      data: {
        type: 'object' as const,
        properties: { links: { type: 'array' as const, uniqueItems: true, items: { type: 'string' as const, route: 'home' } } },
        required: ['links'],
      },
      events: { ping: { description: 'Pings', payload: { type: 'object' as const, description: 'Nothing yet', properties: {} } } },
    }
    expect(generateTypes(schema, 'x.mel.html')).toBe(
      [
        '// Generated by `melzin types` from x.mel.html. Do not edit.',
        "import type { Href } from 'melzin'",
        '',
        'export type Data = {',
        "  links: readonly Href<'home'>[]",
        '}',
        'export type Handlers = {',
        '  /**',
        '   * Pings',
        '   * @param payload Nothing yet',
        '   */',
        '  ping: (payload: Record<string, never>) => void',
        '}',
        '',
      ].join('\n'),
    )
  })

  test('no data', async () => {
    expect(await generated('no-data')).toBe(
      [
        '// Generated by `melzin types` from no-data.mel.html. Do not edit.',
        'export type Data = Record<string, never>',
        'export type Handlers = {',
        '  dismiss: (payload?: undefined) => void',
        '}',
        '',
      ].join('\n'),
    )
  })

  test('no events', async () => {
    expect(await generated('no-events')).toBe(
      [
        '// Generated by `melzin types` from no-events.mel.html. Do not edit.',
        'export type Data = {',
        '  message?: string',
        '}',
        'export type Handlers = Record<string, never>',
        '',
      ].join('\n'),
    )
  })

  test('no schema at all, and empty objects', async () => {
    expect(await generated('static')).toBe(
      [
        '// Generated by `melzin types` from static.mel.html. Do not edit.',
        'export type Data = Record<string, never>',
        'export type Handlers = Record<string, never>',
        '',
      ].join('\n'),
    )
    const schema = { data: { type: 'object' as const, properties: { box: { type: 'object' as const, properties: {} } } }, events: {} }
    expect(generateTypes(schema, 'x.mel.html')).toContain('  box?: Record<string, never>\n')
  })

  test('typesPathFor', () => {
    expect(typesPathFor('/p/views/counter.mel.html')).toBe('/p/views/counter.types.ts')
    expect(typesPathFor('views/profile-card.mel.html')).toBe('views/profile-card.types.ts')
  })
})

describe('melzin types', () => {
  test('writes <name>.types.ts next to each view', async () => {
    const { code, stdout } = await run(['counter.mel.html', 'nested.mel.html'])
    expect(code).toBe(0)
    expect(stdout).toBe('wrote counter.types.ts\nwrote nested.types.ts\n')
    expect(readFileSync(join(dir, 'counter.types.ts'), 'utf8')).toBe(await generated('counter'))
    expect(readFileSync(join(dir, 'nested.types.ts'), 'utf8')).toBe(await generated('nested'))
  })

  test('leaves an up-to-date file untouched', async () => {
    await run(['leaves.mel.html'])
    const before = statSync(join(dir, 'leaves.types.ts')).mtimeMs
    await Bun.sleep(20)
    const { code, stdout } = await run(['leaves.mel.html'])
    expect(code).toBe(0)
    expect(stdout).toBe('leaves.types.ts is up to date\n')
    expect(statSync(join(dir, 'leaves.types.ts')).mtimeMs).toBe(before)
  })

  test('warnings do not block generation', async () => {
    const { code } = await run(['warned.mel.html'])
    expect(code).toBe(0)
    expect(existsSync(join(dir, 'warned.types.ts'))).toBe(true)
  })

  test('refuses (exit 1) when the view has checker errors, and still writes the others', async () => {
    const { code, stdout, stderr } = await run(['broken.mel.html', 'no-events.mel.html'])
    expect(code).toBe(1)
    expect(stderr).toBe(
      [
        "broken.mel.html:14:14: error: m-text: unknown field 'cuont' (did you mean 'count'?)",
        'melzin types: not writing broken.types.ts: broken.mel.html has 1 error (run melzin check)',
        '',
      ].join('\n'),
    )
    expect(stdout).toBe('wrote no-events.types.ts\n')
    expect(existsSync(join(dir, 'broken.types.ts'))).toBe(false)
  })

  test('refuses files that are not views or do not exist', async () => {
    const { code, stderr } = await run(['missing.mel.html'])
    expect(code).toBe(1)
    expect(stderr).toContain("missing.mel.html:1:1: error: can't read the file: file not found")
    expect(existsSync(join(dir, 'missing.types.ts'))).toBe(false)
  })

  test('no files is a usage error (exit 2)', async () => {
    const { code, stderr } = await run([])
    expect(code).toBe(2)
    expect(stderr).toContain('usage: melzin types <files...>')
  })
})
