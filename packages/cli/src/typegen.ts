// Generates a view's host types from its schema (used by `melzin types`, and by `melzin check` to spot
// a stale types file).

import { basename, dirname, join, relative, sep } from 'node:path'
import { type FieldSchema, type MelzinSchema, type ObjectSchema, ROUTES_FILE, type RouteTable, VIEW_FILE_SUFFIX } from 'melzin/core'

const EMPTY = 'Record<string, never>'

function comment(description: string | undefined, indent: string): string[] {
  if (description === undefined || description.trim() === '') return []
  const text = description.replace(/\s+/g, ' ').trim().replaceAll('*/', '*\\/')
  return [`${indent}/** ${text} */`]
}

function objectType(object: ObjectSchema, indent: string): string {
  const entries = Object.entries(object.properties)
  if (entries.length === 0) return EMPTY
  const required = new Set(object.required ?? [])
  const inner = `${indent}  `
  const lines = ['{']
  for (const [name, field] of entries) {
    lines.push(...comment(field.description, inner))
    lines.push(`${inner}${name}${required.has(name) ? '' : '?'}: ${fieldType(field, inner)}`)
  }
  lines.push(`${indent}}`)
  return lines.join('\n')
}

/** A field's type; a list (SPEC D34) is an array of its items' type, inline. */
function fieldType(field: FieldSchema, indent: string): string {
  if (field.type === 'object') return objectType(field, indent)
  if (field.type === 'array') return `${fieldType(field.items, indent)}[]`
  return field.route !== undefined ? `Href<'${field.route}'>` : field.type
}

function handlersType(events: MelzinSchema['events']): string {
  const entries = Object.entries(events ?? {})
  if (entries.length === 0) return EMPTY
  const lines = ['{']
  for (const [name, event] of entries) {
    lines.push(...comment(event.description, '  '))
    lines.push(`  ${name}: (payload?: undefined) => void`)
  }
  lines.push('}')
  return lines.join('\n')
}

function hasLinks(field: FieldSchema): boolean {
  if (field.type === 'object') return Object.values(field.properties).some(hasLinks)
  return field.type === 'array' ? hasLinks(field.items) : field.route !== undefined
}

/**
 * The `.types.ts` source for a view. `sourceName` is the view's file name, for the header. Link fields
 * (SPEC D23) get melzin's `Href` type, which only the href helper produces.
 */
export function generateTypes(schema: MelzinSchema | null, sourceName: string): string {
  const data = schema?.data === undefined ? EMPTY : objectType(schema.data, '')
  return [
    `// Generated by \`melzin types\` from ${sourceName}. Do not edit.`,
    ...(schema?.data !== undefined && hasLinks(schema.data) ? ["import type { Href } from 'melzin'", ''] : []),
    `export type Data = ${data}`,
    `export type Handlers = ${handlersType(schema?.events)}`,
    '',
  ].join('\n')
}

/** `profile-card` → `ProfileCardView`, a name for the view's types in routes.types.ts. */
function viewAlias(view: string, taken: Set<string>): string {
  const words = view.split(/[^A-Za-z0-9]+/).filter((word) => word !== '')
  let alias = `${words.map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join('')}View`
  if (!/^[A-Za-z_]/.test(alias)) alias = `_${alias}`
  let unique = alias
  for (let i = 2; taken.has(unique); i++) unique = `${alias}${i}`
  taken.add(unique)
  return unique
}

function recordType(names: readonly string[], optional: boolean): string {
  if (names.length === 0) return EMPTY
  return `{ ${names.map((name) => `${name}${optional ? '?' : ''}: string`).join('; ')} }`
}

/**
 * The `routes.types.ts` source for a route table: each route's params, query, data and handlers, for
 * a typed source and href helper (`startApp<Routes>`, `hrefs<Routes>`). `typesImport` is the import
 * path of a view's `.types.ts`, relative to the generated file.
 */
export function generateRouteTypes(table: RouteTable, typesImport: (view: string) => string, sourceName = ROUTES_FILE): string {
  const taken = new Set<string>()
  const aliases = new Map<string, string>()
  for (const route of table.routes) if (!aliases.has(route.view)) aliases.set(route.view, viewAlias(route.view, taken))
  const lines = [`// Generated by \`melzin types\` from ${sourceName}. Do not edit.`]
  for (const [view, alias] of aliases) lines.push(`import type * as ${alias} from '${typesImport(view)}'`)
  if (aliases.size > 0) lines.push('')
  if (table.routes.length === 0) {
    lines.push(`export type Routes = ${EMPTY}`, '')
    return lines.join('\n')
  }
  lines.push('export type Routes = {')
  for (const route of table.routes) {
    const alias = aliases.get(route.view)!
    lines.push(...comment(route.description ?? `${route.path}, shown by ${route.view}${VIEW_FILE_SUFFIX}`, '  '))
    lines.push(`  ${route.name}: {`)
    lines.push(`    params: ${recordType(route.params, false)}`)
    lines.push(`    query: ${recordType(route.query, true)}`)
    lines.push(`    data: ${alias}.Data`)
    lines.push(`    handlers: ${alias}.Handlers`)
    lines.push('  }')
  }
  lines.push('}', '')
  return lines.join('\n')
}

/** `/app/routes.json` → `/app/routes.types.ts`. */
export function routeTypesPathFor(routesPath: string): string {
  return join(dirname(routesPath), `${basename(routesPath).replace(/\.json$/, '')}.types.ts`)
}

/** The import path of a view's types from the routes types file: `./views/profile.types.ts`. */
export function viewTypesImport(routeTypesPath: string, viewsDir: string, view: string): string {
  const path = relative(dirname(routeTypesPath), join(viewsDir, `${view}.types.ts`)).split(sep).join('/')
  return path.startsWith('.') ? path : `./${path}`
}

/** `views/counter.mel.html` → `views/counter.types.ts`. */
export function typesPathFor(viewPath: string): string {
  const name = basename(viewPath)
  const stem = name.endsWith(VIEW_FILE_SUFFIX) ? name.slice(0, -VIEW_FILE_SUFFIX.length) : name.replace(/\.[^.]*$/, '')
  return join(dirname(viewPath), `${stem}.types.ts`)
}
